/**
 * ヘキサの縁の太さ。素材の 10 を輪郭と同じ 1.1961 倍にした値である。
 *
 * おにぎりの `SHIELD_STROKE_WIDTH`(15.94)より細い。揃えるより素材のままに
 * した。縁は形の一部で、太さもヘキサがヘキサに見える理由の一つである。
 */
export const HEX_STROKE_WIDTH = 11.96;

/**
 * 路線の呼び名。「長野県道63号」「東京都道7号」「北海道道106号」の形である。
 *
 * 「県道」「都道」「府道」「道道」の呼び分けは、県の名前の末尾が既に持っている。
 * 名前に「道」を継ぐだけで四つとも正しく出るので、呼び分けの表は要らない。
 * Wikipedia の記事名もこの形である(#101)。
 */
export const prefRouteName = (prefLabel, ref) => `${prefLabel}道${ref}号`;

/**
 * 番号を中に入れたヘキサ。
 *
 * 実物の標識は上に「県道」、下に県名を載せる。ここは番号だけにする——操作面での
 * 実寸は高さ 30 px で、その大きさでは上下の段の字は形にならない。読めない字を
 * 描いても、番号を細らせるだけである。どの県かは、標識を出す側が文字で述べる。
 *
 * 県は消えていない。`prefLabel` は読み上げの名前になり、支援技術には
 * 「長野県道63号」と届く。
 *
 * 番号はおにぎりより大きい。ヘキサは胴が広く、上下の段を載せないぶんそこが空く
 * ので、style.css の `.shield.hex text` が `font-size` を 240 に上げている
 * (おにぎりは 212.5)。高さを 22 px まで落とす行——路線の詳細が出す関連路線の
 * 一覧——でも 3 桁が読めるのは、この差である。
 *
 * 桁ごとの幅は、その字の高さで斜辺のあいだに残る幅から取ってある。3 桁と 4 桁は
 * どちらもそこで頭打ちになるので同じ値になる。位置と幅と `font-size` は、
 * `HEX_VIEWBOX` に対して目で三つまとめて合わせてある。
 */
export function hexShield(prefLabel, ref, small) {
  const digits = String(ref).length;
  const width = digits >= 3 ? 326 : digits === 2 ? 267 : 134;
  return (
    `<span class="shield hex${small ? ' sm' : ''}">` +
    `<svg viewBox="${HEX_VIEWBOX}" role="img" ` +
    `aria-label="${prefRouteName(prefLabel, ref)}">` +
    `<path d="${HEX_PATH}" stroke-width="${HEX_STROKE_WIDTH}" ` +
    'stroke-linejoin="round"/>' +
    `<text x="244.5" y="303" text-anchor="middle" textLength="${width}" ` +
    `lengthAdjust="spacingAndGlyphs">${ref}</text>` +
    '</svg></span>'
  );
}
